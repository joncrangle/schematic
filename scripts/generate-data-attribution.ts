#!/usr/bin/env bun
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { agencyCatalog } from "../src/agencies/agencyCatalog";
import type { AgencyManifestConfig } from "../src/agencies/types";

type AttributionAgency = Pick<AgencyManifestConfig, "id" | "name" | "attribution">;

function markdownText(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/[\\|`*_[\]]/g, "\\$&")
    .replace(/\r\n|\r|\n/g, "<br>");
}

function markdownLink(label: string, url: string): string {
  const destination = url.replace(/[\s<>|]/g, (character) => encodeURIComponent(character));
  return `[${markdownText(label)}](<${destination}>)`;
}

export function renderDataAttribution(agencies: readonly AttributionAgency[]): string {
  const rows = [...agencies]
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map(({ name, attribution }) => {
      const license = /^https?:\/\/\S+$/.test(attribution.license)
        ? markdownLink("Licence terms", attribution.license)
        : markdownText(attribution.license);
      return `| ${markdownText(name)} | ${markdownLink(attribution.name, attribution.url)} | ${license} |`;
    });

  return [
    "<!-- Generated by bun run attribution:generate. Edit agency manifests, then regenerate. -->",
    "",
    "# Transit data attribution",
    "",
    "Schematic uses transit data from the sources below. Each source's licence and terms apply to its data separately from the application's software licence.",
    "",
    "This is an independent project, not affiliated with or endorsed by any transit agency.",
    "",
    "| Agency | Data source | Licence or acknowledgement |",
    "| --- | --- | --- |",
    ...rows,
    "",
    "Source links and licence labels are declared in each registered agency's `manifest.attribution`. Consult the linked source for its full terms.",
    "",
    "To add or correct an attribution, follow the [agency guide](add-an-agency.md), update the manifest, and run `bun run attribution:generate`. CI checks this document with `bun run attribution:check`.",
    "",
  ].join("\n");
}

/** Check mode never creates or updates the generated document. */
export function syncDataAttribution(
  outputPath: string,
  agencies: readonly AttributionAgency[],
  check: boolean,
): boolean {
  const expected = renderDataAttribution(agencies);
  if (check) {
    return existsSync(outputPath) && readFileSync(outputPath, "utf8") === expected;
  }
  writeFileSync(outputPath, expected);
  return true;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check")) {
    console.error("Usage: bun scripts/generate-data-attribution.ts [--check]");
    process.exitCode = 1;
  } else {
    const check = args.includes("--check");
    const outputPath = resolve(import.meta.dirname, "../docs/data-attribution.md");
    const current = syncDataAttribution(
      outputPath,
      agencyCatalog.map(({ manifest }) => manifest),
      check,
    );
    if (!current) {
      console.error(
        "docs/data-attribution.md is missing or out of date. Run bun run attribution:generate and commit the result.",
      );
      process.exitCode = 1;
    } else {
      console.log(
        `Data attribution ${check ? "checked" : "generated"} for ${agencyCatalog.length} registered agencies.`,
      );
    }
  }
}
