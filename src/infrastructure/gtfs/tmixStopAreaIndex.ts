import type { TmixAnyRideFeed } from "~/infrastructure/realtime/tmix/tmixTransport";
import { processArchiveCsv, readGtfsArchive } from "./archive";

interface StopArea {
  readonly externalId: string;
  readonly text: string;
}
interface RouteStops {
  readonly stops: readonly string[];
  readonly areas: readonly StopArea[];
}
const nameKey = (name: string): string => name.trim().replace(/\s+/gu, " ").toLocaleLowerCase("en");

/** Unique names identify branches; ordered occurrences distinguish repeated street/terminal names. */
export function mapTmixStopAreas(
  names: Readonly<Record<string, string>>,
  routes: readonly RouteStops[],
): Record<string, string> {
  const constraints = new Map<string, Set<string>>();
  for (const route of routes) {
    const groups = new Map<string, string[]>();
    for (const area of route.areas) {
      if (!/^\d+$/u.test(area.externalId)) throw new Error("Invalid AnyRide external stop-area ID");
      const name = nameKey(area.text.replace(/\s+\([^()]+\)$/u, ""));
      groups.set(name, [...(groups.get(name) ?? []), area.externalId]);
    }
    const occurrences = new Map<string, string[]>();
    for (const stop of route.stops) {
      const name = nameKey(names[stop] ?? "");
      occurrences.set(name, [...(occurrences.get(name) ?? []), stop]);
    }
    for (const [name, stops] of occurrences) {
      const areas = groups.get(name) ?? [];
      if (!areas.length) throw new Error(`Unmapped AnyRide GTFS stop: ${stops[0]}`);
      for (const [index, stop] of stops.entries()) {
        // A closed GTFS trip repeats its starting platform; the vendor list omits that repeat.
        const closing = route.stops[0] === route.stops.at(-1) && stop === route.stops[0];
        const candidates =
          areas.length === 1
            ? areas
            : areas.length === stops.length
              ? [areas[index]]
              : closing && areas.length === stops.length - 1
                ? [areas[index % areas.length]]
                : areas;
        if (!candidates.length) throw new Error(`Unmapped AnyRide GTFS stop: ${stop}`);
        const previous = constraints.get(stop);
        const compatible = new Set(candidates.filter((area) => !previous || previous.has(area)));
        if (!compatible.size) throw new Error(`Conflicting AnyRide stop-area mapping: ${stop}`);
        constraints.set(stop, compatible);
      }
    }
  }
  const result: Record<string, string> = {};
  for (const [stop, candidates] of constraints) {
    if (candidates.size !== 1) throw new Error(`Unmapped ambiguous AnyRide GTFS stop: ${stop}`);
    result[stop] = [...candidates][0];
  }
  return Object.fromEntries(Object.entries(result).sort(([a], [b]) => a.localeCompare(b)));
}

/** Regenerated by the seed CLI for tenants whose GTFS IDs are not AnyRide queries. */
export async function buildTmixStopAreaIndex(
  archives: readonly Uint8Array[],
  feed: TmixAnyRideFeed,
  fetchImpl: typeof fetch = fetch,
): Promise<Record<string, string>> {
  const names: Record<string, string> = {};
  const trips = new Map<string, string>();
  const sequences = new Map<string, { stop: string; sequence: number }[]>();
  const routeNames = new Map<string, string>();
  for (const bytes of archives) {
    const archive = readGtfsArchive(bytes);
    await processArchiveCsv(archive, "stops.txt", ["stop_id", "stop_name"], (get) => {
      names[get("stop_id")] = get("stop_name");
    });
    await processArchiveCsv(
      archive,
      "routes.txt",
      ["route_id", "route_short_name", "route_long_name"],
      (get) => {
        routeNames.set(get("route_id"), get("route_short_name") || get("route_long_name"));
      },
    );
    await processArchiveCsv(archive, "trips.txt", ["trip_id", "route_id"], (get) => {
      trips.set(get("trip_id"), get("route_id"));
    });
    await processArchiveCsv(
      archive,
      "stop_times.txt",
      ["trip_id", "stop_id", "stop_sequence"],
      (get) => {
        const trip = get("trip_id");
        const rows = sequences.get(trip) ?? [];
        rows.push({ stop: get("stop_id"), sequence: Number(get("stop_sequence")) });
        sequences.set(trip, rows);
      },
    );
  }
  const headers: Record<string, string> = { "Content-Type": "application/json" };
  if (feed.profile) {
    headers["anyride-profile-data"] = feed.profile.data;
    if (feed.profile.display) headers["anyride-profile-display"] = feed.profile.display;
  }
  const areasByRoute = new Map<string, StopArea[]>();
  // GetLines is tenant scoped by the same profile as GetCalls. Never derive vendor IDs by arithmetic.
  const post = async (endpoint: string, body: unknown): Promise<unknown> => {
    const response = await fetchImpl(`${feed.url.replace(/\/+$/u, "")}/${endpoint}`, {
      method: "POST",
      headers,
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(20_000),
    });
    if (!response.ok) throw new Error(`AnyRide ${endpoint}: HTTP ${response.status}`);
    return response.json();
  };
  const linesResponse = await fetchImpl(`${feed.url.replace(/\/+$/u, "")}/GetLines`, {
    headers,
    signal: AbortSignal.timeout(20_000),
  });
  if (!linesResponse.ok) throw new Error(`AnyRide GetLines: HTTP ${linesResponse.status}`);
  const lines: unknown = await linesResponse.json();
  if (!Array.isArray(lines)) throw new Error("Invalid AnyRide lines");
  for (const routeId of new Set(trips.values())) {
    const matching = lines.filter(
      (candidate) =>
        String(candidate.id).startsWith(feed.operatorPrefix) &&
        (String(candidate.externalId) === routeId ||
          nameKey(String(candidate.text)) ===
            nameKey(`${routeNames.get(routeId)} - ${routeNames.get(routeId)}`)),
    );
    if (matching.length !== 1)
      throw new Error(`Missing or ambiguous AnyRide line for GTFS route ${routeId}`);
    const line = matching[0];
    const areas = await post("GetStopAreas", { lineId: line.id });
    if (
      !Array.isArray(areas) ||
      !areas.length ||
      areas.some((area) => typeof area.externalId !== "string" || typeof area.text !== "string")
    )
      throw new Error(`Invalid AnyRide stop areas for route ${routeId}`);
    areasByRoute.set(routeId, areas);
  }
  return mapTmixStopAreas(
    names,
    [...sequences].map(([trip, rows]) => ({
      stops: rows.sort((a, b) => a.sequence - b.sequence).map((row) => row.stop),
      areas: areasByRoute.get(trips.get(trip)!) ?? [],
    })),
  );
}
