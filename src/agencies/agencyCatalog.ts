export interface AgencyDefinition {
  readonly manifest: AgencyManifestConfig;
  /** Omit this file for a mapless agency. */
  readonly schematic?: Schematic;
}

function decodeManifest(raw: unknown): AgencyManifestConfig {
  // The client build imports trimmed manifests (see
  // scripts/lib/agency-schematics-vite-plugin.ts) that only the browser
  // registry reads, and it validates their browser fields itself.
  if (isBrowserManifest(raw)) return raw as AgencyManifestConfig;
  return Schema.decodeUnknownSync(AgencyManifestConfigSchema)(raw);
}

function decodeSchematic(raw: unknown): Schematic | undefined {
  // The client build resolves these imports to `undefined` (see
  // scripts/lib/agency-schematics-vite-plugin.ts); the browser loads
  // schematics lazily through `loadSchematic`.
  if (raw === undefined) return undefined;
  return Schema.decodeUnknownSync(SchematicSchema)(raw);
}

